# Builds ref.cpp: the DuXun plugin's own CPU pixel code (copied verbatim by line range from
# DuXunFilmSim.cpp), driven by a raw image + a "name value" params file instead of OpenFX.
# Usage: python make_harness.py <DuXunFilmSim.cpp> <out ref.cpp>
import re, sys

src = open(sys.argv[1], encoding='utf-8').read().split('\n')
L = lambda a, b: '\n'.join(src[a - 1:b])  # 1-based inclusive

decls = L(4098, 4132)
names = re.findall(r'\b(?:double|int)\s+([^;]+);', decls)
variables = []
for group in names:
    for part in group.split(','):
        variables.append(part.split('=')[0].strip())
overrides = '\n'.join(f'        if (!strcmp(key, "{v}")) {v} = (decltype({v}))value;' for v in variables)

harness = f'''// GENERATED by make_harness.py from DuXunFilmSim.cpp (GPL-2.0-or-later). Test use only.
#include <cstring>
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstdint>
#include <string>
#include <vector>
typedef int OfxStatus;

{L(60, 666)}

{L(678, 1570)}

int main(int argc, char** argv) {{
    if (argc < 4) {{ fprintf(stderr, "usage: ref in.raw params.txt out.raw\\n"); return 2; }}
    FILE* fi = fopen(argv[1], "rb"); int width = 0, height = 0;
    fread(&width, 4, 1, fi); fread(&height, 4, 1, fi);
    std::vector<float> srcv((size_t)width * height * 4), dstv((size_t)width * height * 4);
    fread(srcv.data(), 4, srcv.size(), fi); fclose(fi);
    double renderTime = 0.0;
{decls}
    FILE* fp = fopen(argv[2], "r"); char key[128]; double value;
    while (fscanf(fp, "%127s %lf", key, &value) == 2) {{
{overrides}
    }}
    fclose(fp);
{L(4300, 4417)}
    float* __restrict src = srcv.data();
    float* __restrict dst = dstv.data();
    int sS = width * 4, dS = width * 4;
    float invW = 1.0f / (float)width, invH = 1.0f / (float)height;
{L(4449, 4504)}
{L(4534, 4550)}
    renderRows(args, 0, height);
    freeGlowBuffer(halationGlow); freeGlowBuffer(bloomGlow);
    FILE* fo = fopen(argv[3], "wb"); fwrite(&width, 4, 1, fo); fwrite(&height, 4, 1, fo);
    fwrite(dstv.data(), 4, dstv.size(), fo); fclose(fo);
    return 0;
}}
'''
open(sys.argv[2], 'w', encoding='utf-8').write(harness)
print(len(variables), 'parameters')
